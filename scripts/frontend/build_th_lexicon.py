"""Build the Thai word list src/vtts/frontend/lexicons/th/words.txt.

Usage: uv run python scripts/frontend/build_th_lexicon.py [--min-freq 20]

Source: PyThaiNLP's corpus data (pythainlp 5.x, dev dependency only, never used at run time):
words_th.txt (Thai word list) and tnc_freq.txt (word frequencies from the Thai National Corpus),
both released by the PyThaiNLP project under CC0-1.0.

- Words of Thai letters only, at least two characters, with a TNC frequency of at least
  --min-freq (the word list holds many rare compounds and names).
- The list only places word boundaries; readings come from the rules (and overrides.tsv).
- The keys of lexicons/th/overrides.tsv are always words (the runtime adds them itself).
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path

import pythainlp

from vtts.frontend.th.g2p_th import override_table

OUT = Path(__file__).parents[2] / "src" / "vtts" / "frontend" / "lexicons" / "th" / "words.txt"
THAI_WORD = re.compile(r"[ก-ฮะ-ฺเ-๎]{2,}")
HEADER = ("# Thai words for word segmentation (th/g2p_th.segment), one per line.\n"
          "# Generated by scripts/frontend/build_th_lexicon.py from PyThaiNLP's words_th.txt\n"
          "# and tnc_freq.txt (CC0-1.0).\n")


def corpus(name: str) -> Path:
    return Path(pythainlp.__file__).parent / "corpus" / name


def candidates(min_freq: int) -> list[str]:
    freq: dict[str, int] = {}
    for line in corpus("tnc_freq.txt").read_text(encoding="utf-8").splitlines():
        w, _, f = line.partition("\t")
        if f.isdigit():
            freq[w] = int(f)
    words = {w.strip() for w in corpus("words_th.txt").read_text(encoding="utf-8").splitlines()}
    return sorted((w for w in words if THAI_WORD.fullmatch(w) and freq.get(w, 0) >= min_freq),
                  key=lambda w: (len(w), w))


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--min-freq", type=int, default=20)
    a = ap.parse_args()
    words = candidates(a.min_freq)
    overrides = set(override_table())
    kept = sorted(w for w in words if w not in overrides)
    OUT.write_text(HEADER + "".join(w + "\n" for w in kept), encoding="utf-8")
    size = sum(len(w.encode("utf-8")) + 1 for w in kept)
    print(f"{len(words)} candidates, {len(kept)} words, {size / 1024:.0f} KiB")


if __name__ == "__main__":
    main()
