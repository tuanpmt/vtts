"""Build the Lao word list src/vtts/frontend/lexicons/lo/words.txt.

Usage: uv run python scripts/frontend/build_lo_lexicon.py --spell lo_spellcheck_dict.txt \
       --dict lao-eng-dictionary.csv --wiki PATH/20231101.lo/train-00000-of-00001.parquet \
       [--min-count 2]

Sources (offline only):
- lo_spellcheck_dict.txt of Google's language-resources (https://github.com/google/
  language-resources, lo/data_sets/, Apache-2.0, Copyright 2015 Google Inc.).
- The LaoWord column of lao-eng-dictionary.csv, the Lao-English dictionary of the E-Government
  Center, Ministry of Posts and Telecommunications of Laos (MIT License, Copyright (c) 2015), as
  shipped with LaoNLP.
- Lao Wikipedia (wikimedia/wikipedia 20231101.lo, CC BY-SA): only to count how often each word is
  used; no text is included.

Candidates are words of Lao letters only, at least two characters, in the form prepare() reads
(ໜ ໝ -> ຫນ ຫມ, ໍາ -> ຳ). Every run of Lao letters of Wikipedia is segmented with all candidates
(lo/g2p_lo.segment); a candidate used at least --min-count times is kept. The list only places word
boundaries; readings come from the rules (and overrides.tsv), whose keys are always words.
"""

from __future__ import annotations

import argparse
import csv
import re
from collections import Counter
from pathlib import Path

from vtts.frontend.lo.g2p_lo import override_table, prepare, segment

OUT = Path(__file__).parents[2] / "src" / "vtts" / "frontend" / "lexicons" / "lo" / "words.txt"
LAO_WORD = re.compile(r"[ກ-ໍໜ-ໟ]{2,}")
LAO_RUN = re.compile(r"[ກ-ໍໜ-ໟ]+")
HEADER = ("# Lao words for word segmentation (lo/g2p_lo.segment), one per line, in prepared form.\n"
          "# Generated by scripts/frontend/build_lo_lexicon.py from Google's lo_spellcheck_dict.txt\n"
          "# (Apache-2.0) and the E-Government Center's Lao-English dictionary (MIT), kept when used\n"
          "# in Lao Wikipedia.\n")


def candidates(spell: Path, dictionary: Path) -> set[str]:
    words = {ln.strip() for ln in spell.read_text(encoding="utf-8-sig").splitlines()
             if ln.strip() and not ln.startswith("#")}
    with dictionary.open(encoding="utf-8") as f:
        words |= {row["LaoWord"].strip() for row in csv.DictReader(f)}
    return {prepare(w) for w in words if LAO_WORD.fullmatch(w)}


def main() -> None:
    import pyarrow.parquet as pq

    ap = argparse.ArgumentParser()
    ap.add_argument("--spell", type=Path, required=True)
    ap.add_argument("--dict", type=Path, required=True)
    ap.add_argument("--wiki", type=Path, nargs="+", required=True)
    ap.add_argument("--min-count", type=int, default=2)
    a = ap.parse_args()
    cands = candidates(a.spell, a.dict)
    maxw = max(map(len, cands))
    counts: Counter = Counter()
    seen: Counter = Counter()
    for p in a.wiki:
        for text in pq.read_table(p, columns=["text"]).column("text").to_pylist():
            for run in LAO_RUN.findall(text):
                for piece in prepare(run).split("ໆ"):
                    if piece:
                        seen[piece] += 1
    for piece, n in seen.items():
        for w in segment(piece, cands, maxw):
            if w in cands:
                counts[w] += n
    overrides = set(override_table())
    kept = sorted(w for w, n in counts.items() if n >= a.min_count and w not in overrides)
    OUT.write_text(HEADER + "".join(w + "\n" for w in kept), encoding="utf-8")
    size = sum(len(w.encode("utf-8")) + 1 for w in kept)
    print(f"{len(cands)} candidates, {len(kept)} words, {size / 1024:.0f} KiB")


if __name__ == "__main__":
    main()
