"""Build the Mandarin reading tables src/vtts/frontend/lexicons/zh/{chars,phrases}.tsv.

Usage: uv run python scripts/frontend/build_zh_lexicon.py

Source: pypinyin's bundled data (MIT license; dev dependency only, never used at run time).
- Characters: the 6763 Han characters of GB2312 plus the characters of pypinyin's phrase list
  (an offline stand-in for the 8105-character Tongyong Guifan list), each with pypinyin's first
  (most common) reading as the default.
- Phrases: pypinyin's 2-4 character phrases made of those characters, kept only when the runtime
  (forward maximum matching over the shorter kept phrases, then per-character defaults) would
  read them differently without the entry. Sandhi tones of 一 and 不 baked into pypinyin's phrases are
  reset to citation tones (yi1, bu4) because the front-end applies no sandhi (see g2p_zh).
- lexicons/zh/overrides.tsv (hand-edited) wins over pypinyin: a one-character key sets that
  character's default, a longer key sets a phrase reading.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import pypinyin
from pypinyin.contrib.tone_convert import to_tone3
from pypinyin.phrases_dict import phrases_dict
from pypinyin.pinyin_dict import pinyin_dict

from vtts.frontend.lexicons import load_table
from vtts.frontend.zh.g2p_zh import MAX_PHRASE, is_han, read_han
from vtts.frontend.zh.pinyin import syllable_tokens

OUT = Path(__file__).parents[2] / "src" / "vtts" / "frontend" / "lexicons" / "zh"
CITATION = {("一", "yi2"): "yi1", ("一", "yi4"): "yi1", ("不", "bu2"): "bu4"}


def numbered(marked: str) -> str:
    return to_tone3(marked, neutral_tone_with_five=True)


def gb2312_han() -> set[str]:
    out = set()
    for hi in range(0xB0, 0xF8):
        for lo in range(0xA1, 0xFF):
            try:
                ch = bytes((hi, lo)).decode("gb2312")
            except UnicodeDecodeError:
                continue
            if is_han(ch):
                out.add(ch)
    return out


def char_defaults(charset: set[str]) -> dict[str, str]:
    out = {}
    for ch in sorted(charset):
        for marked in pinyin_dict.get(ord(ch), "").split(","):
            if marked and syllable_tokens(numbered(marked)):
                out[ch] = numbered(marked)
                break
    return out


def gold_phrases(chars: dict[str, str]) -> dict[str, tuple[str, ...]]:
    out = {}
    for phrase, readings in phrases_dict.items():
        if not 2 <= len(phrase) <= MAX_PHRASE or len(readings) != len(phrase):
            continue
        if not all(ch in chars for ch in phrase):
            continue
        syls = tuple(CITATION.get((ch, numbered(r[0])), numbered(r[0]))
                     for ch, r in zip(phrase, readings))
        if all(syllable_tokens(s) for s in syls):
            out[phrase] = syls
    return out


def reduce_phrases(gold: dict[str, tuple[str, ...]], chars: dict[str, str]
                   ) -> dict[str, tuple[str, ...]]:
    """Phrases the runtime needs so that every gold phrase reads correctly.

    Shortest first: a phrase is kept only if the shorter kept phrases and the character defaults
    misread it. An entry only changes texts that contain it, so a later (longer or equal-length)
    entry never breaks an earlier phrase; the final check confirms it."""
    kept: dict[str, tuple[str, ...]] = {}
    for phrase in sorted(gold, key=lambda p: (len(p), p)):
        if tuple(read_han(phrase, chars, kept)) != gold[phrase]:
            kept[phrase] = gold[phrase]
    wrong = [p for p, r in gold.items() if tuple(read_han(p, chars, kept)) != r]
    assert not wrong, wrong[:10]
    return kept


def write(path: Path, rows: dict[str, str], what: str) -> None:
    head = (f"# {what}. Generated by scripts/frontend/build_zh_lexicon.py from pypinyin "
            f"{pypinyin.__version__} (MIT); do not edit, put fixes in overrides.tsv.\n")
    body = "".join(f"{k}\t{v}\n" for k, v in sorted(rows.items()))
    path.write_text(head + body, encoding="utf-8")
    print(f"{path.name}: {len(rows)} entries, {path.stat().st_size} bytes")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=Path, default=OUT)
    a = ap.parse_args()
    overrides = load_table("zh", "overrides")
    for key, reading in overrides.items():
        bad = [s for s in reading.split() if not syllable_tokens(s)]
        if bad or len(reading.split()) != len(key):
            raise SystemExit(f"overrides.tsv: bad reading for {key}: {reading}")
    phrase_chars = {ch for p in phrases_dict for ch in p if is_han(ch) and ord(ch) in pinyin_dict}
    override_chars = {ch for k in overrides for ch in k}
    chars = char_defaults(gb2312_han() | phrase_chars | override_chars)
    chars.update({k: v for k, v in overrides.items() if len(k) == 1})
    gold = gold_phrases(chars)
    gold.update({k: tuple(v.split()) for k, v in overrides.items() if len(k) > 1})
    phrases = reduce_phrases(gold, chars)
    a.out.mkdir(parents=True, exist_ok=True)
    write(a.out / "chars.tsv", chars, "Default reading per character")
    write(a.out / "phrases.tsv", {k: " ".join(v) for k, v in phrases.items()},
          f"Phrases read differently from their characters' defaults ({len(gold)} checked)")


if __name__ == "__main__":
    main()
