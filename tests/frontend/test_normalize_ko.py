    ("3시간", "세 시간"),
    ("1번째", "첫 번째"),
    ("2번째", "두 번째"),
    ("11번째", "열한 번째"),
    # dates (유월, 시월)
    ("2026년 11월 18일", "이천이십육년 십일월 십팔일"),
    ("6월", "유월"),
    ("10월", "시월"),
    ("1월 1일", "일월 일일"),
    ("2026-11-18", "이천이십육년 십일월 십팔일"),
    ("2026. 6. 10.", "이천이십육년 유월 십일"),
