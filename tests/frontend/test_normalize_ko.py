    ("100명", "백 명"),
    ("1,250달러", "천이백오십 달러"),
    # native numbers before native counters (1..99)
    ("사과 3개", "사과 세 개"),
    ("학생 2명", "학생 두 명"),
    ("1명", "한 명"),
    ("20살", "스무 살"),
    ("25살", "스물다섯 살"),
