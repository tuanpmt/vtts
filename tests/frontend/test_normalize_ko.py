    ("₩5,000", "오천 원"),
    ("$20", "이십 달러"),
    ("25℃", "이십오 도"),
    ("5km", "오 킬로미터"),
    ("3kg", "삼 킬로그램"),
    ("3~5개", "셋에서 다섯 개"),
    # product codes and Latin words: English
    ("ESP32-P4", "e s p three two p four"),
    ("Wi-Fi를 켜 주세요.", "wi fi 를 켜 주세요 ."),
    # punctuation
    ("안녕하세요! 반갑습니다…", "안녕하세요 ! 반갑습니다 ,"),
