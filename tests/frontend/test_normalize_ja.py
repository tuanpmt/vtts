"""Japanese normalization (ja/normalize_ja.py): numbers with sound changes, counters, dates."""

import pytest

from vtts.frontend.ja.normalize_ja import cardinal, normalize_ja, with_counter


@pytest.mark.parametrize("n, reading", [
    (0, "ゼロ"), (7, "ナナ"), (10, "ジュー"), (15, "ジューゴ"), (100, "ヒャク"),
    (300, "サンビャク"), (600, "ロッピャク"), (800, "ハッピャク"), (1000, "セン"),
    (3000, "サンゼン"), (8000, "ハッセン"), (2026, "ニセンニジューロク"), (10000, "イチマン"),
    (10000000, "イッセンマン"), (120000000, "イチオクニセンマン"), (10 ** 12, "イッチョー"),
    (-5, "マイナスゴ"),
])
def test_cardinal(n, reading):
    assert cardinal(n) == reading


@pytest.mark.parametrize("num, counter, reading", [
    ("1", "本", "イッポン"), ("2", "本", "ニホン"), ("3", "本", "サンボン"), ("4", "本", "ヨンホン"),
    ("6", "本", "ロッポン"), ("8", "本", "ハッポン"), ("10", "本", "ジュッポン"),
    ("100", "本", "ヒャッポン"), ("1000", "本", "センボン"),
    ("1", "匹", "イッピキ"), ("3", "匹", "サンビキ"),
    ("1", "分", "イップン"), ("2", "分", "ニフン"), ("3", "分", "サンプン"), ("4", "分", "ヨンプン"),
    ("5", "分", "ゴフン"), ("30", "分", "サンジュップン"), ("45", "分", "ヨンジューゴフン"),
    ("1", "個", "イッコ"), ("6", "個", "ロッコ"), ("10", "個", "ジュッコ"),
    ("1", "回", "イッカイ"), ("8", "回", "ハッカイ"), ("3", "階", "サンガイ"),
    ("1", "歳", "イッサイ"), ("6", "歳", "ロクサイ"), ("8", "歳", "ハッサイ"), ("20", "歳", "ハタチ"),
    ("1", "人", "ヒトリ"), ("2", "人", "フタリ"), ("3", "人", "サンニン"), ("4", "人", "ヨニン"),
    ("14", "人", "ジューヨニン"), ("1", "つ", "ヒトツ"), ("3", "つ", "ミッツ"), ("10", "つ", "トー"),
    ("4", "円", "ヨエン"), ("1000", "円", "センエン"), ("4", "年", "ヨネン"),
    ("2024", "年", "ニセンニジューヨネン"),
    ("4", "時", "ヨジ"), ("7", "時", "シチジ"), ("9", "時", "クジ"),
    ("4", "月", "シガツ"), ("9", "月", "クガツ"), ("11", "月", "ジューイチガツ"),
    ("2", "日", "フツカ"), ("8", "日", "ヨーカ"), ("20", "日", "ハツカ"), ("24", "日", "ニジューヨッカ"),
    ("18", "日", "ジューハチニチ"), ("3", "日間", "ミッカカン"),
    ("1", "か月", "イッカゲツ"), ("1", "週間", "イッシューカン"),
])
def test_counters(num, counter, reading):
    assert with_counter(num, counter) == reading


def test_first_of_the_month():
    assert with_counter("1", "日", after_month=True) == "ツイタチ"
    assert with_counter("1", "日") == "イチニチ"
    assert normalize_ja("11月1日") == "ジューイチガツツイタチ"


@pytest.mark.parametrize("text, out", [
    ("2026年11月18日", "ニセンニジューロクネンジューイチガツジューハチニチ"),
    ("2026-11-18", "ニセンニジューロクネンジューイチガツジューハチニチ"),
    ("9時30分", "クジサンジュップン"),
    ("9:30", "クジサンジュップン"),
    ("18:00", "ジューハチジ"),
    ("15%", "ジューゴパーセント"),
    ("3.14", "サンテンイチヨン"),
    ("-5度", "マイナスゴド"),
    ("1234567", "イチニサンヨンゴロクナナ"),          # 5 or more digits: one by one
    ("1,234円", "センニヒャクサンジューヨエン"),
    ("100000円", "ジューマンエン"),                 # a counter keeps the number
    ("3万人", "サンマンニン"),
    ("1億2000万", "イチオクニセンマン"),
    ("¥500", "ゴヒャクエン"),
    ("$20", "ニジュードル"),
    ("3〜5個", "サンカラゴコ"),
    ("090-1234-5678", "ゼロキューゼロノイチニサンヨンノゴロクナナハチ"),
    ("5km", "ゴキロメートル"),
    ("２０２６年", "ニセンニジューロクネン"),            # full-width digits
    ("3分の1", "サンブンノイチ"),
])
def test_numbers_in_text(text, out):
    assert normalize_ja(text) == out


def test_punctuation_and_latin():
    assert normalize_ja("「こんにちは」と言った。") == "こんにちはと言った ."
    assert normalize_ja("東京・大阪…京都！本当？") == "東京大阪 , 京都 ! 本当 ?"
    assert normalize_ja("ESP32-P4は2個です") == "e s p three two p four はニコです"
    assert normalize_ja("Wi-Fiを設定") == "wi fi を設定"
    assert normalize_ja("今日は 晴れ") == "今日は晴れ"       # no spaces inside Japanese text
