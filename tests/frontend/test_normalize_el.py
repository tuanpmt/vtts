import pytest

from vtts.frontend.el.normalize_el import cardinal, gender_of, normalize_el, ordinal


@pytest.mark.parametrize("n, g, words", [
    (0, "n", "μηδέν"), (1, "n", "ένα"), (1, "m", "ένας"), (1, "f", "μία"), (3, "n", "τρία"),
    (3, "f", "τρεις"), (4, "n", "τέσσερα"), (4, "m", "τέσσερις"), (13, "n", "δεκατρία"),
    (13, "f", "δεκατρείς"), (14, "f", "δεκατέσσερις"), (21, "n", "είκοσι ένα"),
    (21, "f", "είκοσι μία"), (100, "n", "εκατό"), (101, "n", "εκατόν ένα"),
    (234, "n", "διακόσια τριάντα τέσσερα"), (234, "f", "διακόσιες τριάντα τέσσερις"),
    (200, "m", "διακόσιοι"), (1000, "n", "χίλια"), (1000, "f", "χίλιες"), (1001, "n", "χίλια ένα"),
    (2026, "n", "δύο χιλιάδες είκοσι έξι"), (3000, "n", "τρεις χιλιάδες"),
    (21000, "n", "είκοσι μία χιλιάδες"), (200000, "n", "διακόσιες χιλιάδες"),
    (1_000_000, "n", "ένα εκατομμύριο"), (2_500_000, "n", "δύο εκατομμύρια πεντακόσιες χιλιάδες"),
    (3 * 10 ** 9, "n", "τρία δισεκατομμύρια"), (-7, "n", "μείον επτά"),
])
def test_cardinal(n, g, words):
    assert cardinal(n, g) == words


@pytest.mark.parametrize("n, ending, words", [
    (1, "ος", "πρώτος"), (2, "η", "δεύτερη"), (3, "ο", "τρίτο"), (8, "ος", "όγδοος"),
    (11, "ος", "ενδέκατος"), (13, "η", "δέκατη τρίτη"), (20, "ός", "εικοστός"),
    (21, "ο", "εικοστό πρώτο"), (100, "ος", "εκατοστός"), (123, "η", "εκατοστή εικοστή τρίτη"),
])
def test_ordinal(n, ending, words):
    assert ordinal(n, ending) == words


@pytest.mark.parametrize("word, g", [
    ("παιδιά", "n"), ("ευρώ", "n"), ("αδελφές", "f"), ("θέσεις", "f"), ("ώρα", "f"), ("μαΐου", "f"),
    ("φίλους", "m"), ("άνθρωποι", "m"), (None, "n"),
])
def test_gender_of(word, g):
    assert gender_of(word) == g


