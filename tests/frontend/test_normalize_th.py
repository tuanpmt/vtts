"""Thai normalization (th/normalize_th.py): numbers, dates, times, spaces as pauses."""

import pytest

from vtts.frontend.th.normalize_th import cardinal, normalize_th, number


@pytest.mark.parametrize("n, words", [
    (0, "ศูนย์"), (1, "หนึ่ง"), (10, "สิบ"), (11, "สิบเอ็ด"), (20, "ยี่สิบ"), (21, "ยี่สิบเอ็ด"),
    (25, "ยี่สิบห้า"), (100, "หนึ่งร้อย"), (101, "หนึ่งร้อยเอ็ด"), (111, "หนึ่งร้อยสิบเอ็ด"),
    (1001, "หนึ่งพันเอ็ด"), (12345, "หนึ่งหมื่นสองพันสามร้อยสี่สิบห้า"), (200000, "สองแสน"),
    (1_000_000, "หนึ่งล้าน"), (1_000_001, "หนึ่งล้านหนึ่ง"), (21_000_000, "ยี่สิบเอ็ดล้าน"),
    (2_100_021, "สองล้านหนึ่งแสนยี่สิบเอ็ด"), (-5, "ลบห้า"),
])
def test_cardinal(n, words):
    assert cardinal(n) == words


def test_decimals():
    assert number("3.14") == "สามจุดหนึ่งสี่"
    assert number("1,250") == "หนึ่งพันสองร้อยห้าสิบ"


@pytest.mark.parametrize("text, out", [
    ("ราคา 100 บาท", "ราคาหนึ่งร้อยบาท"),                  # spaces around numbers are not pauses
    ("มี ๒๑ คน", "มียี่สิบเอ็ดคน"),                          # Thai digits
    ("ขึ้น 5% เป็น 3.14", "ขึ้นห้าเปอร์เซ็นต์เป็นสามจุดหนึ่งสี่"),
    ("เวลา 14:30 น.", "เวลาสิบสี่นาฬิกาสามสิบนาที"),
    ("เวลา 07.05 น.", "เวลาเจ็ดนาฬิกาห้านาที"),
    ("วันที่ 19/11/2569", "วันที่สิบเก้าพฤศจิกายนสองพันห้าร้อยหกสิบเก้า"),
    ("พ.ศ. 2567", "พุทธศักราชสองพันห้าร้อยหกสิบเจ็ด"),
    ("1 ม.ค.", "หนึ่งมกราคม"),
    ("ราคา ฿1,500", "ราคาหนึ่งพันห้าร้อยบาท"),
    ("โทร 081-234-5678", "โทรศูนย์แปดหนึ่งสองสามสี่ห้าหกเจ็ดแปด"),
    ("ตั้งแต่ 10-20 คน", "ตั้งแต่สิบถึงยี่สิบคน"),
    ("อุณหภูมิ 25°C", "อุณหภูมิยี่สิบห้าองศาเซลเซียส"),
    ("ไปกรุงเทพฯ", "ไปกรุงเทพมหานคร"),
    ("ผัก ผลไม้ ฯลฯ", "ผัก , ผลไม้ , และอื่นๆ"),
    ("เด็ก ๆ เล่นกัน", "เด็กๆเล่นกัน"),
])
def test_normalize(text, out):
    assert normalize_th(text) == out


def test_space_between_thai_runs_is_a_pause():
    assert normalize_th("ไม่ตอบสนองเลย ช่วยดูให้หน่อย") == "ไม่ตอบสนองเลย , ช่วยดูให้หน่อย"


def test_latin_goes_to_english_and_codes_are_spelled():
    assert normalize_th("เปิด ESP32") == "เปิด e s p สามสอง"
    assert normalize_th("ใช้ Netflix") == "ใช้ netflix"
