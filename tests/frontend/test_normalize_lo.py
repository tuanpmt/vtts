import pytest

from vtts.frontend.lo.normalize_lo import cardinal, normalize_lo


@pytest.mark.parametrize("n, words", [
    (0, "ສູນ"), (1, "ໜຶ່ງ"), (10, "ສິບ"), (11, "ສິບເອັດ"), (20, "ຊາວ"), (21, "ຊາວເອັດ"),
    (35, "ສາມສິບຫ້າ"), (101, "ໜຶ່ງຮ້ອຍເອັດ"), (1000, "ໜຶ່ງພັນ"), (25_000, "ສອງໝື່ນຫ້າພັນ"),
    (150_000, "ໜຶ່ງແສນຫ້າໝື່ນ"), (2_000_000, "ສອງລ້ານ"), (1_000_001, "ໜຶ່ງລ້ານໜຶ່ງ"), (-5, "ລົບຫ້າ"),
])
def test_cardinal(n, words):
    assert cardinal(n) == words


@pytest.mark.parametrize("text, out", [
    ("ມີ 21 ຄົນ", "ມີຊາວເອັດຄົນ"),
    ("ມີ ໓໒ ຄົນ", "ມີສາມສິບສອງຄົນ"),
    ("ລາຄາ 125,000 ກີບ", "ລາຄາໜຶ່ງແສນສອງໝື່ນຫ້າພັນກີບ"),
    ("₭5,000", "ຫ້າພັນກີບ"),
    ("ເວລາ 14:30", "ເວລາສິບສີ່ໂມງສາມສິບນາທີ"),
    ("ວັນທີ 5/3/2026", "ວັນທີຫ້າມີນາສອງພັນຊາວຫົກ"),
    ("ເພີ່ມ 12.5%", "ເພີ່ມສິບສອງຈຸດຫ້າເປີເຊັນ"),
    ("ໄລຍະ 120 ກມ.", "ໄລຍະໜຶ່ງຮ້ອຍຊາວກິໂລແມັດ"),
    ("ໂທ 020 5512 3456", "ໂທສູນສອງສູນຫ້າຫ້າໜຶ່ງສອງສາມສີ່ຫ້າຫົກ"),
    ("ອາຍຸ 10-20 ປີ", "ອາຍຸສິບຫາຊາວປີ"),
    ("ສະບາຍດີ ຂ້ອຍຊື່ແກ້ວ", "ສະບາຍດີ , ຂ້ອຍຊື່ແກ້ວ"),
    ("ເປີດ Wi-Fi ໃຫ້ແດ່", "ເປີດ wi fi ໃຫ້ແດ່"),
    ("ບອດ ESP32", "ບອດ e s p ສາມສອງ"),
    ("ໄວ ໆ ນີ້ ຯລຯ", "ໄວໆນີ້ , ແລະອື່ນໆ"),
])
def test_normalize(text, out):
    assert normalize_lo(text) == out
