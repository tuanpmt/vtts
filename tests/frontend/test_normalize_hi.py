"""Hindi normalization (hi/normalize_hi.py): numbers, dates, times, money, digits, marks."""

import pytest

from vtts.frontend.hi.normalize_hi import cardinal, normalize_hi, number_words, year
from vtts.frontend.lexicons import load_table


def test_numbers_table_covers_0_to_99():
    table = number_words()
    assert len(table) == 100 and set(table) == set(range(100))
    assert len(set(table.values())) == 100
    assert load_table("hi", "numbers")["0"] == "शून्य"


@pytest.mark.parametrize("n, words", [
    (0, "शून्य"), (1, "एक"), (5, "पाँच"), (6, "छह"), (9, "नौ"), (10, "दस"), (11, "ग्यारह"),
    (15, "पंद्रह"), (19, "उन्नीस"), (21, "इक्कीस"), (25, "पच्चीस"), (29, "उनतीस"),
    (33, "तैंतीस"), (38, "अड़तीस"), (45, "पैंतालीस"), (49, "उनचास"), (51, "इक्यावन"),
    (59, "उनसठ"), (67, "सड़सठ"), (69, "उनहत्तर"), (75, "पचहत्तर"), (79, "उनासी"), (80, "अस्सी"),
    (89, "नवासी"), (90, "नब्बे"), (99, "निन्यानबे"),
])
def test_cardinal_table(n, words):
    assert cardinal(n) == words


@pytest.mark.parametrize("n, words", [
    (100, "एक सौ"), (101, "एक सौ एक"), (250, "दो सौ पचास"), (999, "नौ सौ निन्यानबे"),
    (1000, "एक हज़ार"), (1947, "एक हज़ार नौ सौ सैंतालीस"), (25000, "पच्चीस हज़ार"),
    (100000, "एक लाख"), (125000, "एक लाख पच्चीस हज़ार"), (9999999, "निन्यानबे लाख निन्यानबे हज़ार नौ सौ निन्यानबे"),
    (10000000, "एक करोड़"), (25000000, "दो करोड़ पचास लाख"),
    (1000000000, "एक सौ करोड़"), (-5, "माइनस पाँच"),
])
def test_cardinal_large(n, words):
    assert cardinal(n) == words


def test_years():
    assert year(1947) == "उन्नीस सौ सैंतालीस"
    assert year(1900) == "उन्नीस सौ"
    assert year(2026) == "दो हज़ार छब्बीस"


