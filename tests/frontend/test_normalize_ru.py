"""Russian normalization (ru/normalize_ru.py)."""

import pytest

from vtts.frontend.ru.normalize_ru import cardinal, cardinal_gen, normalize_ru, ordinal, plural


@pytest.mark.parametrize("n, gender, words", [
    (0, "m", "ноль"), (1, "m", "один"), (1, "f", "одна"), (1, "n", "одно"), (2, "f", "две"),
    (11, "f", "одиннадцать"), (21, "f", "двадцать одна"), (100, "m", "сто"),
    (1000, "m", "тысяча"), (2000, "m", "две тысячи"), (5000, "m", "пять тысяч"),
    (21000, "m", "двадцать одна тысяча"), (1999, "m", "тысяча девятьсот девяносто девять"),
    (2026, "m", "две тысячи двадцать шесть"), (1_000_000, "m", "один миллион"),
    (2_500_000, "m", "два миллиона пятьсот тысяч"), (-5, "m", "минус пять"),
])
def test_cardinal(n, gender, words):
    assert cardinal(n, gender) == words


@pytest.mark.parametrize("n, case, words", [
    (1, "nom_m", "первый"), (2, "nom_f", "вторая"), (3, "nom_m", "третий"), (3, "gen_m", "третьего"),
    (3, "nom_f", "третья"), (21, "gen_m", "двадцать первого"), (40, "nom_m", "сороковой"),
    (100, "nom_m", "сотый"), (300, "prep_m", "трёхсотом"), (1000, "nom_m", "тысячный"),
    (2000, "nom_m", "двухтысячный"), (2026, "gen_m", "две тысячи двадцать шестого"),
    (1990, "gen_pl", "тысяча девятьсот девяностых"), (15, "nom_n", "пятнадцатое"),
])
def test_ordinal(n, case, words):
    assert ordinal(n, case) == words


def test_plural_and_genitive():
    forms = ("рубль", "рубля", "рублей")
    assert [plural(n, forms) for n in (1, 2, 5, 11, 12, 21, 22, 25, 111)] == [
        "рубль", "рубля", "рублей", "рублей", "рублей", "рубль", "рубля", "рублей", "рублей"]
    assert cardinal_gen(32) == "тридцати двух" and cardinal_gen(2500) == "двух тысяч пятисот"
    assert cardinal_gen(100) == "ста" and cardinal_gen(1000) == "тысячи"


