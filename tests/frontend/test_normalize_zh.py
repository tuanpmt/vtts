import pytest

from vtts.frontend.zh.normalize_zh import cardinal, normalize_zh


@pytest.mark.parametrize("n, words", [
    (0, "零"), (2, "二"), (10, "十"), (15, "十五"), (20, "二十"), (105, "一百零五"),
    (110, "一百一十"), (123, "一百二十三"), (1000, "一千"), (1010, "一千零一十"),
    (10010, "一万零一十"), (12345, "一万二千三百四十五"), (100000, "十万"),
    (100000000, "一亿"), (120000000, "一亿二千万"), (100005000, "一亿零五千"), (-7, "负七"),
])
def test_cardinal(n, words):
    assert cardinal(n) == words


@pytest.mark.parametrize("text, out", [
    ("你好，世界！", "你好 , 世界 !"),
    ("第一、第二；第三：完。", "第一 , 第二 ; 第三 : 完 ."),
    ("他说：“好的”（真的）", "他说 : 好的真的"),
    ("共123个", "共一百二十三个"),
    ("圆周率3.14", "圆周率三点一四"),
    ("0.5倍", "零点五倍"),
    ("增长15%", "增长百分之十五"),
    ("增长１５％", "增长百分之十五"),
    ("2026年", "二零二六年"),
    ("11月18日", "十一月十八日"),
    ("2026-11-18", "二零二六年十一月十八日"),
    ("9:30开会", "九点三十分开会"),
    ("9:05", "九点零五分"),
    ("18:00", "十八点"),
    ("气温-5度", "气温负五度"),
    ("电话13812345678", "电话一三八一二三四五六七八"),
    ("人口1,250,000", "人口一百二十五万"),
    ("3~5天", "三到五天"),
    ("价格¥99", "价格九十九元"),
    ("25℃", "二十五摄氏度"),
    ("ESP32-P4芯片", "e s p 三二 p 四芯片"),
    ("5G网络", "五 g 网络"),
    ("好……吧", "好 , 吧"),
])
def test_normalize_zh(text, out):
    assert normalize_zh(text) == out
