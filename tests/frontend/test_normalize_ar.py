def test_normalize(text, expected):
    assert bare(normalize_ar(text)) == expected


def test_generated_words_carry_vowels():
    out = normalize_ar("21")
    assert out == "وَاحِد وَعِشْرُون"


def test_latin_parts_go_to_the_english_normalizer():
    assert normalize_ar("افتح Wi-Fi") == "افتح wi fi"
