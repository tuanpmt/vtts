"""Generate runtime/src/vtts_text_sent_tables.h: the word lists of the sentence-language rule of the
Latin-script pair modes and the vi mode (vtts.frontend.latin.sentence_is_english).

Run: uv run python runtime/tools/gen_sent_tables.py
"""

from pathlib import Path

from vtts.frontend.latin import LATIN_PAIRS, _sentence_sets
from vtts.frontend.lexicons import load_words

OUT = Path(__file__).resolve().parents[1] / "src" / "vtts_text_sent_tables.h"


def c_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def c_list(name: str, items: list[str]) -> list[str]:
    items = sorted(items)  # strcmp order: the lists are ASCII
    out = [f"static const char *const {name}[{max(len(items), 1)}] = {{"]
    out += ["    " + ", ".join(c_str(s) for s in items[i:i + 8]) + "," for i in range(0, len(items), 8)]
    if not items:
        out.append('    "",')
    return out + ["};", f"#define {name}_N {len(items)}", ""]


def header() -> str:
    """The text of vtts_text_sent_tables.h."""
    out = ["/* SPDX-License-Identifier: Apache-2.0 */",
           "/* Generated by runtime/tools/gen_sent_tables.py from src/vtts/frontend/lexicons; do not edit.",
           " * Word lists of the sentence-language rule (latin.sentence_is_english): sorted lower-case ASCII. */",
           "#ifndef VTTS_TEXT_SENT_TABLES_H", "#define VTTS_TEXT_SENT_TABLES_H", ""]
    out += c_list("VTTS_SENT_STRONG", list(load_words("latin", "function_en")))
    out += c_list("VTTS_SENT_COMMON", list(load_words("latin", "common_en")))
    words = [w for code in LATIN_PAIRS for s in _sentence_sets(code)[:2] for w in s]
    words += load_words("latin", "function_en") | load_words("latin", "common_en") | load_words("latin", "english")
    out += [f"#define VTTS_SENT_MAX_KEY {max(map(len, words))} /* the longest word of any list */", ""]
    for code, letters in LATIN_PAIRS.items():
        main, both = _sentence_sets(code)[:2]
        out += [f"#if VTTS_ENABLE_{code.upper()}"]
        out += c_list(f"VTTS_SENT_MAIN_{code.upper()}", list(main))
        out += c_list(f"VTTS_SENT_BOTH_{code.upper()}", list(both))
        out += [f"static const char VTTS_SENT_OWN_{code.upper()}[] = {c_str(letters)};", "#endif", ""]
    out += ["#endif", ""]
    return "\n".join(out)


def main() -> None:
    OUT.write_text(header(), encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
