"""Generate the Khmer and Burmese tables of the device front-end from the Python sources:
runtime/src/vtts_text_km_tables.h and runtime/src/vtts_text_my_tables.h (called by
gen_text_tables.py; run: uv run python runtime/tools/gen_text_tables.py).

Khmer letters are coded as code point - 0x1780 + 1 (0x01..0x5E) and Burmese letters as code point
- 0x1000 + 1 (0x01..0xA0) in the byte strings of the tables.
"""

from __future__ import annotations

from pathlib import Path

SRC = Path(__file__).resolve().parents[1] / "src"
KM_OUT = SRC / "vtts_text_km_tables.h"
MY_OUT = SRC / "vtts_text_my_tables.h"
KM0, MY0 = 0x1780, 0x1000


def c_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def hexs(bs) -> str:
    """A C string literal of bytes (none may be 0)."""
    assert all(0 < b < 256 for b in bs), bs
    return '"' + "".join(f"\\x{b:02x}" for b in bs) + '"'


def km_code(ch: str) -> int:
    c = ord(ch) - KM0 + 1
    assert 1 <= c <= 0x5E, ch
    return c


def front_coded(keys: list[bytes], block: int) -> tuple[bytes, list[int]]:
    """Sorted byte keys, front coded: 0x80 | shared starts each key (codes < 0x80 follow); the
    first key of each block shares nothing. A final 0x80 ends the data."""
    data, offsets, prev = bytearray(), [], b""
    for k, w in enumerate(keys):
        p = 0
        if k % block:
            while p < min(len(prev), len(w)) and prev[p] == w[p]:
                p += 1
        else:
            offsets.append(len(data))
        assert p < 0x80 and all(b < 0x80 for b in w)
        data.append(0x80 | p)
        data.extend(w[p:])
        prev = w
    data.append(0x80)
    return bytes(data), offsets


def blob_lines(name: str, data: bytes) -> list[str]:
    out = [f"static const uint8_t {name}[{len(data)}] = {{"]
    for i in range(0, len(data), 24):
        out.append("    " + ",".join(str(b) for b in data[i:i + 24]) + ",")
    return out + ["};"]


def word_char(ch: str) -> int:
    return int(ch.isalnum() or ch == "_")


# ---------------- Khmer ----------------

def khmer_tables() -> list[str]:
    from vtts.frontend import phoneme_set as ps
    from vtts.frontend.km import g2p_km as g
    from vtts.frontend.km import normalize_km as nk

    idx = ps.token_index("km-en")
    out = ["/* SPDX-License-Identifier: Apache-2.0 */",
           "/* generated by runtime/tools/gen_text_tables.py (gen_nsp_tables.py) -- do not edit */",
           "#ifndef VTTS_TEXT_KM_TABLES_H", "#define VTTS_TEXT_KM_TABLES_H", "#include <stdint.h>", ""]
    flags = {"CONS": 1, "INDEP": 2, "SERIES_O": 4, "SONORANT": 8, "DEP": 16, "SIGN": 32, "UPPER": 64,
             "BANTOC": 128, "SILENCER": 256, "ROBAT": 512, "IGNORED": 1024, "WORD": 2048, "LETTER": 4096,
             "KHMER": 8192, "MUUS": 16384, "TRII": 32768}
    out += [f"#define VTTS_KM_{k} {v}u" for k, v in flags.items()]
    fin_names = ["-", "k", "ŋ", "c", "ɲ", "t", "n", "p", "m", "j", "r", "l", "w", "h", "ʔ", "R"]
    letters = []
    import re
    letter_re = re.compile("[" + nk.LETTERS + "]")
    for c in range(KM0, KM0 + 128):
        ch = chr(c)
        f = 0
        f |= flags["CONS"] * (ch in g.ONSET)
        f |= flags["INDEP"] * (ch in g.INDEPENDENT)
        f |= flags["SERIES_O"] * (ch in g.SERIES_O)
        f |= flags["SONORANT"] * (ch in g.SONORANTS)
        f |= flags["DEP"] * (ch in g.DEP_VOWELS)
        f |= flags["SIGN"] * (ch in g.SIGNS)
        f |= flags["UPPER"] * (ch in g.UPPER)
        f |= flags["BANTOC"] * (ch == g.BANTOC)
        f |= flags["SILENCER"] * (ch in g.SILENCERS)
        f |= flags["ROBAT"] * (ch == g.ROBAT)
        f |= flags["IGNORED"] * (ch in g.IGNORED)
        f |= flags["WORD"] * word_char(ch)
        f |= flags["LETTER"] * bool(letter_re.match(ch))
        f |= flags["KHMER"] * g.is_khmer(ch)
        f |= flags["MUUS"] * (ch == g.MUUSIKATOAN)
        f |= flags["TRII"] * (ch == g.TRIISAP)
        onset = idx["KM:" + g.ONSET_TOKEN.get(g.ONSET[ch], g.ONSET[ch])] if ch in g.ONSET else 0
        fin = fin_names.index(g.FINAL[ch]) if ch in g.FINAL else 0
        row = g.ROW.get(ch, 7)
        letters.append((f, onset, fin, row, ch))
    out += ["typedef struct { uint16_t flags; uint8_t onset, fin, row; } vtts_km_letter;",
            "static const vtts_km_letter VTTS_KM_LETTERS[128] = {  /* code point - 0x1780 */"]
    out += [f"    {{{f}, {o}, {fi}, {r}}},  /* U+{KM0 + k:04X} */" for k, (f, o, fi, r, ch) in enumerate(letters)]
    out += ["};", ""]
    out += [f"#define VTTS_KM_FIN_{n} {k}" for k, n in
            ((0, "NONE"), (fin_names.index("r"), "R"), (fin_names.index("R"), "ROBAT"))]
    # final sound -> final token id (0: no token: r, R, none)
    fin_tok = []
    for n in fin_names:
        name = g.FINAL_TOKEN.get(n, n)
        fin_tok.append(idx.get("KM:F:" + name, 0) if n not in ("-", "r", "R") else 0)
    out += ["static const uint8_t VTTS_KM_FIN_TOKEN[] = {" + ", ".join(map(str, fin_tok)) + "};"]
    # robat as a final letter: the key byte of its final
    out += [f"#define VTTS_KM_FINCODE_ROBAT {fin_names.index('R')}"]
    tok = lambda name: idx[name]
    out += [f"#define VTTS_KM_T_AA {tok('KM:AA')}", f"#define VTTS_KM_T_OO {tok('KM:OO')}",
            f"#define VTTS_KM_T_P {tok('KM:p')}", f"#define VTTS_KM_T_F {tok('KM:f')}",
            f"#define VTTS_KM_T_G {tok('KM:g')}", f"#define VTTS_KM_T_Z {tok('KM:z')}",
            f"#define VTTS_KM_T_KH {tok('KM:kh')}", f"#define VTTS_KM_T_K {tok('KM:k')}",
            f"#define VTTS_KM_T_CH {tok('KM:ch')}", f"#define VTTS_KM_T_C {tok('KM:c')}",
            f"#define VTTS_KM_T_TH {tok('KM:th')}", f"#define VTTS_KM_T_T {tok('KM:t')}",
            f"#define VTTS_KM_T_PH {tok('KM:ph')}", f"#define VTTS_KM_T_B {tok('KM:b')}", ""]
    # loan onsets: (first two letters) -> token
    out += ["static const struct { uint8_t a, b, tok; } VTTS_KM_LOAN[] = {"]
    for k, v in g.LOAN_ONSETS.items():
        out.append(f"    {{{km_code(k[0])}, {km_code(k[1])}, {idx['KM:' + v]}}},  /* {k} */")
    out += ["};", f"#define VTTS_KM_N_LOAN {len(g.LOAN_ONSETS)}", ""]
    out += ["static const char VTTS_KM_EXTRA_SPLIT[] = " + hexs([km_code(c) for p in sorted(g.EXTRA_SPLIT) for c in p])
            + ";  /* pairs */", f"#define VTTS_KM_N_EXTRA_SPLIT {len(g.EXTRA_SPLIT)}", ""]
    def tok_bytes(phones: list[str]) -> list[int]:
        return [idx[t] for t in g.syllable_tokens(phones)]

    # independent vowels: token ids
    out += ["static const char *const VTTS_KM_INDEP_IDS[128] = {  /* code point - 0x1780: token ids */"]
    for c in range(KM0, KM0 + 128):
        ch = chr(c)
        if ch in g.INDEPENDENT:
            out.append(f"    [{c - KM0}] = {hexs(tok_bytes(g.INDEPENDENT[ch].split()))},  /* {ch} */")
    out += ["};", ""]

    def key_bytes(key: str) -> bytes:
        series, rest = key[0], key[1:]
        sig, fin, pos = rest.split("|")
        b = [int(series)] + [km_code(c) for c in sig] + [0x60 + fin_names.index(fin)]
        b.append({"e": 0x78, "c": 0x79, "m": 0x7A}[pos])
        return bytes(b)

    rh = sorted((key_bytes(k), tok_bytes(v.split())) for k, v in g.rhyme_table().items())
    out += ["typedef struct { const char *key, *ids; } vtts_km_entry;",
            f"static const vtts_km_entry VTTS_KM_RHYMES[{len(rh)}] = {{  /* sorted keys: series, signs, 0x60 + final, position */"]
    out += [f"    {{{hexs(k)}, {hexs(v)}}}," for k, v in rh]
    out += ["};", f"#define VTTS_KM_N_RHYMES {len(rh)}", ""]
    on = sorted((bytes(km_code(c) for c in k), tok_bytes(v.split())) for k, v in g.onset_table().items())
    out += [f"static const vtts_km_entry VTTS_KM_ONSETS[{len(on)}] = {{  /* sorted letters */"]
    out += [f"    {{{hexs(k)}, {hexs(v) if v else c_str('')}}}," for k, v in on]
    out += ["};", f"#define VTTS_KM_N_ONSETS {len(on)}", ""]
    ov = []
    for k, sylls in g.override_table().items():
        ids = []
        for s in sylls:
            if ids:
                ids.append(0xFF)
            ids += tok_bytes(list(s))
        ov.append((bytes(km_code(c) for c in k), ids))
    ov.sort()
    out += [f"static const vtts_km_entry VTTS_KM_OVERRIDES[{len(ov)}] = {{  /* sorted words: syllables split by 0xff */"]
    out += [f"    {{{hexs(k)}, {hexs(v) if v else c_str('')}}}," for k, v in ov]
    out += ["};", f"#define VTTS_KM_N_OVERRIDES {len(ov)}", ""]
    words = sorted(bytes(km_code(c) for c in w) for w in g.word_set())
    block = 16
    data, offsets = front_coded(words, block)
    out += blob_lines("VTTS_KM_WORDS", data)
    out += [f"#define VTTS_KM_WORDS_BYTES {len(data)}",
            f"static const uint32_t VTTS_KM_BLOCKS[{len(offsets)}] = {{"]
    for i in range(0, len(offsets), 12):
        out.append("    " + ", ".join(str(o) for o in offsets[i:i + 12]) + ",")
    out += ["};", f"#define VTTS_KM_N_BLOCKS {len(offsets)}", f"#define VTTS_KM_MAX_WORD {max(map(len, words))}", ""]
    # normalizer strings
    out += ["static const char *const VTTS_KM_DIGITS[10] = {" + ", ".join(c_str(x) for x in nk.DIGITS) + "};",
            "static const char *const VTTS_KM_TENS[10] = {" + ", ".join(c_str(x) for x in nk.TENS) + "};",
            "static const char *const VTTS_KM_PLACES[4] = {" + ", ".join(c_str(w) for _, w in nk.PLACES) + "};",
            "static const char *const VTTS_KM_MONTHS[13] = {" + ", ".join(c_str(x) for x in nk.MONTHS) + "};"]

    def pairs(name, items):
        return ([f"static const char *const {name}[][2] = {{"] + [f"    {{{c_str(k)}, {c_str(v)}}}," for k, v in items]
                + ["};", f"#define {name.replace('VTTS_KM_', 'VTTS_KM_N_')} {len(items)}"])

    out += pairs("VTTS_KM_UNITS", sorted(nk.UNITS.items(), key=lambda kv: -len(kv[0])))
    out += pairs("VTTS_KM_CURRENCY", list(nk.CURRENCY.items()))
    out += pairs("VTTS_KM_ABBREV", sorted(nk.ABBREVIATIONS.items(), key=lambda kv: -len(kv[0])))
    out += pairs("VTTS_KM_PUNCT", list(nk.PUNCT.items()))
    out += ["static const char *const VTTS_KM_SYMBOLS[5] = {" + ", ".join(c_str(nk.SYMBOLS[k]) for k in "+=&@×") + "};"]
    out += ["static const char *const VTTS_KM_DEDUPE[] = {" + ", ".join(c_str(x) for x in nk.SPEC.dedupe) + "};",
            f"#define VTTS_KM_N_DEDUPE {len(nk.SPEC.dedupe)}"]
    for k in ("MILLION", "MINUS"):
        out.append(f"#define VTTS_KM_{k} {c_str(getattr(nk, k))}")
    out += [f"#define VTTS_KM_POINT {c_str(nk.SPEC.point)}", f"#define VTTS_KM_TO {c_str(nk.SPEC.to)}",
            f"#define VTTS_KM_PERCENT {c_str(nk.SPEC.percent)}", ""]
    out += ["#endif", ""]
    return out


def write() -> None:
    KM_OUT.write_text("\n".join(khmer_tables()), encoding="utf-8")
    print(f"wrote {KM_OUT}")
    MY_OUT.write_text("\n".join(burmese_tables()), encoding="utf-8")
    print(f"wrote {MY_OUT}")


def burmese_tables() -> list[str]:
    """Tables of the Burmese front-end (my/zawgyi.py, my/g2p_my.py, my/normalize_my.py)."""
    import re

    from vtts.frontend import phoneme_set as ps
    from vtts.frontend.my import g2p_my as g
    from vtts.frontend.my import normalize_my as nm
    from vtts.frontend.my import zawgyi as z

    idx = ps.token_index("my-en")
    out = ["/* SPDX-License-Identifier: Apache-2.0 */",
           "/* generated by runtime/tools/gen_text_tables.py (gen_nsp_tables.py) -- do not edit */",
           "#ifndef VTTS_TEXT_MY_TABLES_H", "#define VTTS_TEXT_MY_TABLES_H", "#include <stdint.h>", ""]
    flags = {"CONS": 1, "INDEP": 2, "MEDIAL": 4, "VSIGN": 8, "LETTER": 16, "WORD": 32, "BURMESE": 64,
             "ONSET": 128}
    out += [f"#define VTTS_MY_{k} {v}u" for k, v in flags.items()]
    letter_re = re.compile("[" + nm.LETTERS + "]")
    rows = []
    for c in range(MY0, MY0 + 160):
        ch = chr(c)
        f = 0
        f |= flags["CONS"] * (ch in z.CONSONANTS)
        f |= flags["INDEP"] * (ch in z.INDEPENDENT)
        f |= flags["MEDIAL"] * (ch in g.MEDIALS)
        f |= flags["VSIGN"] * (ch in g.VOWEL_SIGNS)
        f |= flags["LETTER"] * bool(letter_re.match(ch))
        f |= flags["WORD"] * word_char(ch)
        f |= flags["BURMESE"] * g.is_burmese(ch)
        f |= flags["ONSET"] * (ch in g.ONSET)
        rank = z.RANK.get(ch, 0)
        ons = idx["MY:I:" + g.ONSET[ch]] if ch in g.ONSET else 0
        ha = idx["MY:I:" + g.HA_ONSET.get(ch, g.ONSET[ch])] if ch in g.ONSET else 0
        rows.append((f, rank, ons, ha))
    out += ["typedef struct { uint8_t flags, rank, onset, ha; } vtts_my_letter;",
            "static const vtts_my_letter VTTS_MY_LETTERS[160] = {  /* code point - 0x1000 */"]
    out += [f"    {{{f}, {r}, {o}, {h}}},  /* U+{MY0 + k:04X} */" for k, (f, r, o, h) in enumerate(rows)]
    out += ["};", ""]
    zg = sorted(z.ZG_MAP.items())
    out += ["static const struct { uint16_t cp; const char *u; } VTTS_MY_ZG[] = {  /* Zawgyi -> Unicode; < before, > kinzi */"]
    out += [f"    {{0x{ord(k):04X}, {c_str(v)}}}," for k, v in zg]
    out += ["};", f"#define VTTS_MY_N_ZG {len(zg)}", ""]

    def toks(phones: str) -> list[int]:
        ids = []
        for k, syl in enumerate(phones.split(" . ")):
            if k:
                ids.append(0xFF)
            ids += [idx[t] for t in g.syllable_tokens(syl.split())]
        return ids

    out += ["typedef struct { const char *key, *ids; } vtts_my_entry;",
            "static const vtts_my_entry VTTS_MY_SPECIAL[] = {  /* in order; syllables split by 0xff */"]
    out += [f"    {{{c_str(k)}, {hexs(toks(v))}}}," for k, v in g.SPECIAL.items()]
    out += ["};", f"#define VTTS_MY_N_SPECIAL {len(g.SPECIAL)}", ""]
    out += ["static const vtts_my_entry VTTS_MY_SYLLABLES[] = {"]
    out += [f"    {{{c_str(k)}, {hexs(toks(v))}}}," for k, v in g.SYLLABLES.items()]
    out += ["};", f"#define VTTS_MY_N_SYLLABLES {len(g.SYLLABLES)}", ""]
    out += ["static const char *const VTTS_MY_RESPELL[][2] = {"]
    out += [f"    {{{c_str(a)}, {c_str(b)}}}," for a, b in g.RESPELL]
    out += ["};", f"#define VTTS_MY_N_RESPELL {len(g.RESPELL)}", ""]
    out += ["static const char *const VTTS_MY_INDEP_VOWELS[][2] = {"]
    out += [f"    {{{c_str(a)}, {c_str(b)}}}," for a, b in g.INDEPENDENT.items()]
    out += ["};", f"#define VTTS_MY_N_INDEP_VOWELS {len(g.INDEPENDENT)}", ""]
    out += ["static const char *const VTTS_MY_PARTICLES[] = {" + ", ".join(c_str(p) for p in sorted(g.PARTICLES)) + "};",
            f"#define VTTS_MY_N_PARTICLES {len(g.PARTICLES)}"]
    for name in g.VOWELS:
        out.append(f"#define VTTS_MY_V_{name.replace('@', 'SCHWA')} {idx['MY:V:' + name]}")
    out += [f"#define VTTS_MY_F_N {idx['MY:F:N']}", f"#define VTTS_MY_F_Q {idx['MY:F:?']}",
            f"#define VTTS_MY_G_Y {idx['MY:M:y']}", f"#define VTTS_MY_G_W {idx['MY:M:w']}",
            f"#define VTTS_MY_I_W {idx['MY:I:w']}", f"#define VTTS_MY_I_HNY {idx['MY:I:hny']}",
            f"#define VTTS_MY_I_NY {idx['MY:I:ny']}", f"#define VTTS_MY_I_S {idx['MY:I:S']}"]
    out += [f"#define VTTS_MY_T{i} {idx[f'MY:T{i}']}" for i in range(1, 5)]
    out += [""]
    out += ["static const char *const VTTS_MY_DIGITS[10] = {" + ", ".join(c_str(x) for x in nm.DIGITS) + "};",
            "static const char *const VTTS_MY_PLACES[6] = {" + ", ".join(c_str(w) for _, w in nm.PLACES) + "};",
            "static const char *const VTTS_MY_CREAKY[6] = {" + ", ".join(c_str(nm.CREAKY.get(w, w)) for _, w in nm.PLACES) + "};",
            "static const char *const VTTS_MY_MONTHS[13] = {" + ", ".join(c_str(x) for x in nm.MONTHS) + "};"]

    def pairs(name, items):
        return ([f"static const char *const {name}[][2] = {{"] + [f"    {{{c_str(k)}, {c_str(v)}}}," for k, v in items]
                + ["};", f"#define {name.replace('VTTS_MY_', 'VTTS_MY_N_')} {len(items)}"])

    out += pairs("VTTS_MY_UNITS", sorted(nm.UNITS.items(), key=lambda kv: -len(kv[0])))
    out += pairs("VTTS_MY_CURRENCY", list(nm.CURRENCY.items()))
    out += pairs("VTTS_MY_PUNCT", list(nm.PUNCT.items()))
    out += ["static const char *const VTTS_MY_SYMBOLS[5] = {" + ", ".join(c_str(nm.SYMBOLS[k]) for k in "+=&@×") + "};"]
    out += [f"#define VTTS_MY_MINUS {c_str(nm.MINUS)}", f"#define VTTS_MY_POINT {c_str(nm.SPEC.point)}",
            f"#define VTTS_MY_TO {c_str(nm.SPEC.to)}", f"#define VTTS_MY_PERCENT {c_str(nm.SPEC.percent)}",
            f"#define VTTS_MY_MILLION {c_str(nm.PLACES[0][1])}", ""]
    out += ["#endif", ""]
    return out


if __name__ == "__main__":
    write()
